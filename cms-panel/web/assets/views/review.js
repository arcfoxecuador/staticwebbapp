import { watchDeploy } from "../blocks/save.js";
import { api } from "../core/api.js";
import { $, el, esc } from "../core/dom.js";
import { refreshReviewBadge } from "../core/sidebar.js";
import { isAdmin } from "../core/state.js";
import { confirmModal, loadingScreen, notice, screen } from "../core/ui.js";

// ── Cola de revisión: borradores generados por la automatización ─────────────
export async function showReview() {
  loadingScreen("Cola de revisión");
  let data;
  try { data = await api("/api/posts"); }
  catch (e) { screen("Cola de revisión", "Cola de revisión"); notice("err", esc(e.message)); return; }
  const drafts = (data.posts || []).filter((p) => p.autoGenerated && p.draft);

  const wrap = screen("Cola de revisión", `Cola de revisión${isAdmin() ? ` <button class="page-title-action" id="review-generate">Generar ahora</button>` : ""}`, {
    help: `<h3>Resumen</h3><p>Borradores creados por ${isAdmin() ? `<a href="#automation">Blogs automáticos</a>` : "<b>Blogs automáticos</b>"}. Léelos,
      edítalos y <b>aprueba</b> (publica) o <b>rechaza</b> (a la papelera, restaurable). Nada se publica sin tu visto bueno.</p>`,
  });
  wrap.appendChild(el("p", "wp-subtitle",
    "Entradas que escribió la IA y todavía no están en el sitio. Esta pantalla es el filtro: nada se publica hasta que alguien pulsa “Aprobar y publicar”. Rechazar la manda a la papelera, de donde se puede recuperar."));
  const list = el("div", "review-list");
  wrap.appendChild(list);

  function render() {
    list.innerHTML = "";
    if (!drafts.length) {
      list.appendChild(el("div", "review-empty muted",
        `<b>Todo al día: no hay nada por revisar.</b><span>Cuando ${isAdmin() ? `<a href="#automation">Blogs automáticos</a>` : "<b>Blogs automáticos</b>"} escriba una entrada, aparecerá aquí para que la leas y decidas si se publica.</span>`));
      return;
    }
    drafts.forEach((p) => list.appendChild(card(p)));
  }
  function card(p) {
    const c = el("div", "review-card");
    c.innerHTML = `
      <div class="review-main">
        <div class="review-badges">${p.automationTopic ? `<span class="review-topic">${esc(p.automationTopic)}</span>` : ""}<span class="muted">${esc(p.date || "")}</span></div>
        <h2>${esc(p.title)}</h2>
        <p class="review-excerpt">${esc(p.excerpt || "")}</p>
      </div>
      <div class="review-actions">
        <a class="button" href="#post/${esc(p.slug)}">Revisar / editar</a>
        <button class="button button-primary" data-approve>Aprobar y publicar</button>
        <button class="button-link-delete" data-reject>Rechazar</button>
      </div>`;
    c.querySelector("[data-approve]").addEventListener("click", () => approve(p, c));
    c.querySelector("[data-reject]").addEventListener("click", () => reject(p));
    return c;
  }
  async function approve(p, c) {
    const btn = c.querySelector("[data-approve]"); btn.disabled = true; btn.textContent = "Publicando…";
    try {
      const post = await api(`/api/posts/${p.slug}`);
      const r = await api(`/api/posts/${p.slug}`, { method: "PUT", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ ...post, draft: false, baseSha: post._sha }) });
      drafts.splice(drafts.indexOf(p), 1); render(); refreshReviewBadge();
      notice("ok", `Publicado: <b>${esc(p.title)}</b>. <span id="publish-status"><span class="spinner"></span> Publicando tus cambios…</span>`);
      watchDeploy($("publish-status"), r.url || "");
    } catch (e) { btn.disabled = false; btn.textContent = "Aprobar y publicar"; notice("err", esc(e.message)); }
  }
  async function reject(p) {
    if (!(await confirmModal({ title: "Rechazar borrador", message: `¿Mover "${p.title}" a la papelera? Podrás restaurarlo desde el historial.`, confirmLabel: "Rechazar", danger: true }))) return;
    try {
      await api(`/api/posts/${encodeURIComponent(p.slug)}`, { method: "DELETE" });
      drafts.splice(drafts.indexOf(p), 1); render(); refreshReviewBadge();
      notice("ok", "Borrador movido a la papelera.");
    } catch (e) { notice("err", esc(e.message)); }
  }
  render();

  const gen = $("review-generate");
  if (gen) gen.addEventListener("click", async () => {
    gen.disabled = true; gen.textContent = "Generando…";
    try {
      const r = await api("/api/automation/run", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" });
      notice("ok", `Borrador generado${r.title ? `: <b>${esc(r.title)}</b>` : ""}. Aparece abajo para tu revisión.`);
      const fresh = await api("/api/posts");
      drafts.length = 0;
      drafts.push(...(fresh.posts || []).filter((p) => p.autoGenerated && p.draft));
      render(); refreshReviewBadge();
    } catch (e) { notice("err", esc(e.message)); }
    finally { gen.disabled = false; gen.textContent = "Generar ahora"; }
  });
}

