export function buildMenu() {
  const nav = $("wp-menu");
  nav.innerHTML = "";
  const admin = isAdmin();
  // ¿Hay algún ítem visible (para este rol) entre este índice y el siguiente
  // grupo? Evita renderizar la cabecera de un grupo que quedaría vacío.
  const groupHasVisible = (start) => {
    for (let j = start + 1; j < MENU.length; j++) {
      const it = MENU[j];
      if (it.group) return false;
      if (isHidden(it.view)) continue;
      if (ADMIN_ONLY.has(it.view) && !admin) continue;
      return true;
    }
    return false;
  };
  MENU.forEach((item, i) => {
    if (item.group) { if (groupHasVisible(i)) nav.appendChild(el("div", "menu-group", esc(item.group))); return; }
    if (item.sep) { nav.appendChild(el("div", "menu-sep")); return; }
    if (isHidden(item.view)) return; // pantallas ocultas (ver HIDDEN_VIEWS)
    // Los editores no ven las secciones de admin (apariencia, ajustes).
    if (ADMIN_ONLY.has(item.view) && !admin) return;
    const li = el("div", "menu-item");
    li.dataset.view = item.view;
    const a = el("a", "menu-link", `<span class="menu-ico">${ICONS[item.ico] || ""}</span><span class="menu-label">${item.label}</span>`);
    a.href = "#" + item.view;
    li.appendChild(a);
    if (item.sub) {
      const sub = el("div", "submenu");
      // Cabecera del flyout (visible solo cuando el submenú flota, como en WP).
      sub.appendChild(el("div", "submenu-head", item.label));
      for (const s of item.sub) {
        if (s.hash === "categories" && !admin) continue; // categorías = admin
        const sa = el("a", null, s.label);
        sa.href = "#" + s.hash;
        sa.dataset.hash = s.hash;
        sub.appendChild(sa);
      }
      li.appendChild(sub);
    }
    nav.appendChild(li);
  });
}

// Contador de borradores esperando revisión, junto a "Cola de revisión". Es la
// única señal de que la IA dejó trabajo pendiente: sin ella, un borrador puede
// quedarse semanas sin que nadie entre a esa pantalla.
export async function refreshReviewBadge() {
  const li = document.querySelector("#wp-menu .menu-item[data-view='review']");
  if (!li) return;
  let pending = 0;
  try {
    const data = await api("/api/posts");
    pending = (data.posts || []).filter((p) => p.autoGenerated && p.draft).length;
  } catch { return; } // sin red: mejor sin insignia que con un número inventado
  li.querySelector(".menu-badge")?.remove();
  if (!pending) return;
  const badge = el("span", "menu-badge", String(pending));
  // El número solo no dice nada a un lector de pantalla: "3" → "3 borradores…".
  badge.setAttribute("aria-label", `${pending} borrador${pending === 1 ? "" : "es"} esperando revisión`);
  li.querySelector(".menu-link").appendChild(badge);
}

export function setMenu(view) {
  document.querySelectorAll("#wp-menu .menu-item").forEach((li) => {
    const current = li.dataset.view === view;
    li.classList.toggle("current", current);
    const sub = li.querySelector(".submenu");
    if (sub) sub.querySelectorAll("a").forEach((a) => a.classList.toggle("current", a.dataset.hash === currentHash));
  });
}

